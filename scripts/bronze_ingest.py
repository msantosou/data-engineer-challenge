"""Stage 1 — reproducible, append-free Bronze snapshot from local source files.

Run: python scripts/bronze_ingest.py --input-dir docs/sample-data --db data/marvin.duckdb
The input is read-only; each successful run atomically replaces the Bronze tables.
"""
from __future__ import annotations

import argparse
import logging
from pathlib import Path

import duckdb

LOG = logging.getLogger("bronze")

# Every source is retained independently; rows with CDC operation D are NOT filtered.
# TRY_CAST deliberately preserves invalid source values in _raw_payload for later DQ.
SCHEMAS: dict[str, dict[str, str]] = {
    "transactions": {
        "id": "BIGINT", "transaction_id": "VARCHAR", "merchant_id": "VARCHAR",
        "amount": "DECIMAL(20,2)", "currency": "VARCHAR", "status": "VARCHAR",
        "description": "VARCHAR", "created_at": "TIMESTAMPTZ",
        "updated_at": "TIMESTAMPTZ", "payment_method": "VARCHAR",
        "Op": "VARCHAR", "_timestamp": "TIMESTAMPTZ",
    },
    "reconciliation_runs": {
        "id": "BIGINT", "reference_date": "DATE", "file_name": "VARCHAR",
        "status": "VARCHAR", "total_transactions": "BIGINT",
        "started_at": "TIMESTAMPTZ", "completed_at": "TIMESTAMPTZ",
        "created_at": "TIMESTAMPTZ", "Op": "VARCHAR", "_timestamp": "TIMESTAMPTZ",
    },
    "reconciliation_results": {
        "id": "BIGINT", "run_id": "BIGINT", "transaction_id": "VARCHAR",
        "merchant_id": "VARCHAR", "category": "VARCHAR",
        "internal_amount": "DECIMAL(20,2)",
        "processor_amount": "DECIMAL(20,2)",
        "difference": "DECIMAL(20,2)", "created_at": "TIMESTAMPTZ",
        "Op": "VARCHAR", "_timestamp": "TIMESTAMPTZ",
    },
    "enterprise_company": {
        "id": "BIGINT", "merchant_id": "VARCHAR", "legal_name": "VARCHAR",
        "trade_name": "VARCHAR", "document": "VARCHAR",
        "primary_cnae": "VARCHAR", "created_at": "TIMESTAMPTZ",
        "updated_at": "TIMESTAMPTZ", "Op": "VARCHAR",
        "_timestamp": "TIMESTAMPTZ",
    },
    "paysettler": {
        "transaction_id": "VARCHAR", "merchant_id": "VARCHAR",
        "amount": "DECIMAL(20,2)", "currency": "VARCHAR",
        "settled_at": "TIMESTAMPTZ", "processor_reference": "VARCHAR",
        "status": "VARCHAR",
    },
}


def quote_ident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def sql_path(path: Path) -> str:
    return "'" + str(path).replace("'", "''") + "'"


def input_files(input_dir: Path) -> dict[str, list[Path]]:
    patterns = {
        "transactions": "transactions_batch_*.parquet",
        "reconciliation_runs": "reconciliation_runs.parquet",
        "reconciliation_results": "reconciliation_results.parquet",
        "enterprise_company": "enterprise_company.parquet",
    }
    found = {name: sorted(input_dir.glob(pattern)) for name, pattern in patterns.items()}
    # Fixture uses settlement_paysettler.csv; larger generated sets may use settlement_*.csv.
    found["paysettler"] = sorted(set(input_dir.glob("settlement*.csv")))
    missing = [name for name, paths in found.items() if not paths]
    if missing:
        raise FileNotFoundError(f"Missing required sources in {input_dir}: {', '.join(missing)}")
    return found


def select_columns(schema: dict[str, str], available: set[str]) -> str:
    result = []
    for name, datatype in schema.items():
        if name not in available:
            result.append(f"CAST(NULL AS {datatype}) AS {quote_ident(name)}")
        else:
            source = f"s.{quote_ident(name)}"
            # PaySettler CSV may contain comma decimals, as explicitly generated by dirty mode.
            normalized = (
                f"REPLACE(TRIM(CAST({source} AS VARCHAR)), ',', '.')"
                if datatype.startswith("DECIMAL")
                else source
            )
            result.append(f"TRY_CAST({normalized} AS {datatype}) AS {quote_ident(name)}")
    return ",\n            ".join(result)


def ingest(input_dir: Path, db_path: Path) -> dict[str, int]:
    input_dir = input_dir.expanduser().resolve()
    db_path = db_path.expanduser().resolve()
    found = input_files(input_dir)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    counts: dict[str, int] = {}

    con = duckdb.connect(str(db_path))
    try:
        con.execute("BEGIN TRANSACTION")
        con.execute("CREATE SCHEMA IF NOT EXISTS bronze")
        for source_name, paths in found.items():
            path_sql = "[" + ", ".join(sql_path(p) for p in paths) + "]"
            if source_name == "paysettler":
                reader = f"read_csv({path_sql}, header=true, all_varchar=true, filename=true)"
            else:
                reader = f"read_parquet({path_sql}, union_by_name=true, filename=true)"

            # Inspect available source columns, including schema drift across batches.
            probe = con.execute(f"DESCRIBE SELECT * FROM {reader}").fetchall()
            available = {row[0] for row in probe}
            required = {"transaction_id"} if source_name in ("transactions", "paysettler") else {"id"}
            if not required.issubset(available):
                raise ValueError(f"{source_name}: missing required columns {required - available}")
            fields = select_columns(SCHEMAS[source_name], available)
            con.execute(f"""
                CREATE OR REPLACE TABLE bronze.{quote_ident(source_name)} AS
                SELECT
                    {fields},
                    s.filename::VARCHAR AS _source_file,
                    row_number() OVER ()::BIGINT AS _ingestion_row_number,
                    current_timestamp AS _ingested_at,
                    to_json(s)::VARCHAR AS _raw_payload
                FROM {reader} AS s
            """)
            count = con.execute(
                f"SELECT COUNT(*) FROM bronze.{quote_ident(source_name)}"
            ).fetchone()[0]
            counts[source_name] = count
            LOG.info("bronze.%s: %s rows, %s files", source_name, count, len(paths))

        con.execute("COMMIT")
    except Exception:
        con.execute("ROLLBACK")
        raise
    finally:
        con.close()
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description="Load Bronze from Parquet CDC + PaySettler CSV")
    parser.add_argument("--input-dir", type=Path, default=Path("docs/sample-data"))
    parser.add_argument("--db", type=Path, default=Path("data/marvin.duckdb"))
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    for name, count in ingest(args.input_dir, args.db).items():
        print(f"bronze.{name}: {count} rows")


if __name__ == "__main__":
    main()
